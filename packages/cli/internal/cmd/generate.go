// Package cmd provides the generate command for code generation.
package cmd

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
)

var generateCmd = &cobra.Command{
	Use:     "generate [type] [name]",
	Aliases: []string{"gen", "g"},
	Short:   "Generate code scaffolds",
	Long: `Generate code scaffolds for various o9nn components.

Available generators:
  agent       Generate an agent scaffold
  tool        Generate a tool/function scaffold
  model       Generate a model wrapper scaffold
  plugin      Generate a plugin scaffold
  api         Generate API bindings from schema
  docs        Generate documentation templates

Examples:
  cogctl generate agent my-assistant
  cogctl generate tool calculator --language python
  cogctl generate model custom-llm --backend onnx
  cogctl generate plugin my-extension`,
	Args: cobra.MinimumNArgs(2),
	RunE: func(cmd *cobra.Command, args []string) error {
		genType := args[0]
		name := args[1]
		language, _ := cmd.Flags().GetString("language")
		outputDir, _ := cmd.Flags().GetString("output")
		force, _ := cmd.Flags().GetBool("force")

		return runGenerate(genType, name, language, outputDir, force)
	},
}

func runGenerate(genType, name, language, outputDir string, force bool) error {
	if outputDir == "" {
		outputDir = "."
	}

	fmt.Printf("Generating %s: %s\n", genType, name)
	fmt.Printf("  Language: %s\n", language)
	fmt.Printf("  Output:   %s\n", outputDir)
	fmt.Println()

	switch genType {
	case "agent":
		return generateAgent(name, language, outputDir, force)
	case "tool":
		return generateTool(name, language, outputDir, force)
	case "model":
		return generateModel(name, language, outputDir, force)
	case "plugin":
		return generatePlugin(name, language, outputDir, force)
	case "api":
		return generateAPI(name, language, outputDir, force)
	case "docs":
		return generateDocs(name, outputDir, force)
	default:
		return fmt.Errorf("unknown generator type: %s", genType)
	}
}

